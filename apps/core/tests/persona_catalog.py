def build_scenarios() -> list[Scenario]:
    """台帳を展開する。62画面 × 4ペルソナ × 10案。"""

    scenarios: list[Scenario] = []

    for screen in SCREENS:
        label, noun, category = SCREEN_META.get(
            screen.url_name, (screen.url_name, "データ", "その他")
        )
        templates = TEMPLATES_BY_KIND[screen.kind]

        for persona, _, _, _ in PERSONAS:
            for index, (story, expectation, verdict) in enumerate(templates[persona]):
                override = SPECIFICS.get((screen.url_name, persona, index))

                if override is not None:
                    story, expectation, verdict = override

                scenarios.append(
                    Scenario(
                        screen=screen.url_name,
                        screen_label=label,
                        category=category,
                        persona=persona,
                        index=index + 1,
                        story=story.format(label=label, noun=noun),
                        expectation=expectation.format(label=label, noun=noun),
                        verdict=verdict,
                    )
                )

    return scenarios


def counts() -> dict[str, int]:
    scenarios = build_scenarios()

    return {
        "total": len(scenarios),
        AUTO: sum(1 for s in scenarios if s.verdict == AUTO),
        MANUAL: sum(1 for s in scenarios if s.verdict == MANUAL),
        GAP: sum(1 for s in scenarios if s.verdict == GAP),
    }
